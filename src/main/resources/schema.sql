CREATE TABLE IF NOT EXISTS rateMPAA (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
rate_MPAA VARCHAR UNIQUE
);

CREATE TABLE IF NOT EXISTS film (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR NOT NULL,
description VARCHAR (200),
releaseDate DATE,
duration INTEGER NOT NULL,
rating_id BIGINT REFERENCES rateMPAA (id)
);

CREATE TABLE IF NOT EXISTS category (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
category_name VARCHAR UNIQUE
);

CREATE TABLE IF NOT EXISTS film_category (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
film_id BIGINT REFERENCES film (id),
category_id BIGINT REFERENCES category,
UNIQUE (film_id, category_id)
);

CREATE TABLE IF NOT EXISTS film_rate (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
film_id BIGINT UNIQUE REFERENCES film (id),
rate integer
);

CREATE TABLE IF NOT EXISTS users (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
email VARCHAR NOT NULL,
login VARCHAR NOT NULL,
name VARCHAR,
birthday DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS likes (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
film_id BIGINT REFERENCES film (id),
user_id BIGINT REFERENCES users (id),
UNIQUE (film_id, user_id)
);

CREATE TABLE IF NOT EXISTS status (
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
status_name VARCHAR UNIQUE
);

CREATE TABLE IF NOT EXISTS friends (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_id BIGINT REFERENCES users,
friend_id BIGINT REFERENCES users,
status_id INTEGER REFERENCES status,
UNIQUE (user_id, friend_id)
);